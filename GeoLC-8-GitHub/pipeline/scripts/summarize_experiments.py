#!/usr/bin/env python3
"""Collect completed benchmark runs into machine- and paper-ready tables."""

from __future__ import annotations

import csv
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
RUNS = [
    ("segmentation", "unet_resnet50"),
    ("segmentation", "segformer_b2"),
    ("segmentation", "rs3mamba"),
    ("segmentation", "dinov2_b14_mask2former"),
    ("da", "daformer"),
    ("da", "mic"),
    ("da", "mrm"),
    ("dg", "rein"),
    ("dg", "crossearth"),
    ("dg", "depthforge"),
]
DISPLAY = {
    "unet_resnet50": "U-Net--R50",
    "segformer_b2": "SegFormer-B2",
    "rs3mamba": "RS3Mamba",
    "dinov2_b14_mask2former": "DINOv2-B/14",
    "daformer": "DAFormer",
    "mic": "MIC",
    "mrm": "MRM",
    "rein": "Rein",
    "crossearth": "CrossEarth",
    "depthforge": "DepthForge",
}
REGIONS = ["Indonesia_Agam", "Libya_Zawiya", "Pakistan_Chamla", "Thailand_DoiLang", "Indonesia_Soko"]


def pct(value):
    return f"{100 * value:.2f}"


def main():
    base = ROOT / "pipeline/experiments/runs"
    records = []
    for task, method in RUNS:
        path = base / task / method / "result.json"
        if not path.exists():
            continue
        result = json.loads(path.read_text())
        test = result["test"]
        row = {
            "task": task,
            "method": method,
            "best_epoch": result["best_epoch"],
            "miou": test["miou"],
            "mean_f1": test["mean_f1"],
            "overall_accuracy": test["overall_accuracy"],
            "boundary_f1": test["boundary_f1"],
            **{f"iou_class_{i + 1}": value for i, value in enumerate(test["per_class_iou"])},
        }
        for region, metrics in test.get("regions", {}).items():
            row[f"miou_{region}"] = metrics["miou"]
        records.append(row)

    base.mkdir(parents=True, exist_ok=True)
    (base / "summary.json").write_text(json.dumps(records, indent=2) + "\n")
    if records:
        fields = sorted({key for row in records for key in row})
        with (base / "summary.csv").open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=fields)
            writer.writeheader()
            writer.writerows(records)

    latex = ["% Auto-generated by pipeline/scripts/summarize_experiments.py"]
    for row in records:
        name = DISPLAY[row["method"]]
        if row["task"] == "segmentation":
            values = [pct(row[f"iou_class_{i}"]) for i in range(1, 9)]
            values += [pct(row[key]) for key in ("miou", "mean_f1", "overall_accuracy", "boundary_f1")]
        elif row["task"] == "da":
            values = [pct(row[key]) for key in ("miou", "mean_f1", "overall_accuracy", "boundary_f1")] + ["15"]
        else:
            region_values = [row[f"miou_{region}"] for region in REGIONS]
            values = [pct(value) for value in region_values] + [pct(sum(region_values) / len(region_values))]
        latex.append(name + " & " + " & ".join(values) + r"\\")
    (base / "paper_rows.tex").write_text("\n".join(latex) + "\n", encoding="utf-8")
    print(f"Collected {len(records)}/{len(RUNS)} completed runs")


if __name__ == "__main__":
    main()
